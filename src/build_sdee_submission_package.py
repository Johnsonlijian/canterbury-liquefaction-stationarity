"""Hash and zip the self-contained SDEE Paper B candidate package.

The zip uses fixed timestamps and permissions so a second run over unchanged
files produces the same bytes. The package remains local-only; this script does
not upload or submit anything.
"""
from __future__ import annotations

import hashlib
import sys
import zipfile
from pathlib import Path


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main(package: Path, zip_path: Path) -> None:
    package = package.resolve()
    zip_path = zip_path.resolve()
    manifest = package / "MANIFEST_SHA256.txt"
    files = sorted(p for p in package.rglob("*") if p.is_file() and p != manifest)
    lines = [f"# SHA-256 manifest for {package.name}; generated by build_sdee_submission_package.py"]
    lines.extend(f"{sha256(p)}  {p.relative_to(package).as_posix()}" for p in files)
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    files = sorted(p for p in package.rglob("*") if p.is_file())
    if zip_path.exists():
        zip_path.unlink()
    fixed_date = (2026, 10, 12, 0, 0, 0)
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in files:
            arc = p.relative_to(package.parent).as_posix()
            info = zipfile.ZipInfo(arc, date_time=fixed_date)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 0
            info.external_attr = 0o100644 << 16
            z.writestr(info, p.read_bytes())
    print(f"files={len(files)}")
    print(f"zip={zip_path}")
    print(f"sha256(zip)={sha256(zip_path)}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
